"""Desired testbed state (design §5 "Desired state"; decision 0013).

`config/desired_state.yaml` is the canonical snapshot a clean testbed must match. It is
generated from the rendered testbed manifests and the topology, and committed. It's
version-controlled, and its hash goes into run provenance.
tests/test_snapshot.py regenerates it and fails on any drift, so editing a manifest without
regenerating it (`make desired-state`) can't go unnoticed.

    python -m safeops.environment.desired write
"""

from __future__ import annotations

import sys
from pathlib import Path

from safeops.environment import snapshot as snap

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
DESIRED_STATE_PATH = REPO_ROOT / "config" / "desired_state.yaml"


def _selects(selector: dict, labels: dict) -> bool:
    return bool(selector) and all(labels.get(k) == v for k, v in selector.items())


def desired_snapshot() -> snap.Snapshot:
    from safeops import manifests
    from safeops.cluster import load_cluster_config
    from safeops.topology import load_topology

    cfg, topo = load_cluster_config(), load_topology()
    values = manifests.template_values(cfg, manifests.image_refs())
    objects = [
        o for f in manifests.manifest_files("testbed") for o in manifests.load_objects(f, values)
    ]
    workloads = [o for o in objects if o["kind"] in ("Deployment", "StatefulSet")]

    def owner_of(kind: str, name: str) -> str:
        spec = topo.resource(kind, name)
        return spec.owner if spec is not None else f"unmapped:{kind}/{name}"

    out: dict = {}
    for obj in objects:
        kind, name = obj["kind"], obj["metadata"]["name"]
        if kind == "Deployment":
            out[(kind, name)] = snap.deployment(obj)
        elif kind == "StatefulSet":
            out[(kind, name)] = snap.statefulset(obj)
            for tpl in obj["spec"].get("volumeClaimTemplates") or []:
                for i in range(obj["spec"].get("replicas", 1)):
                    pvc_name = f"{tpl['metadata']['name']}-{name}-{i}"
                    out[("PersistentVolumeClaim", pvc_name)] = {"bound": True}
        elif kind == "ConfigMap":
            spec = topo.resource("ConfigMap", name)
            out[(kind, name)] = snap.configmap(obj, spec.approved_keys if spec else None)
        elif kind == "Service":
            selector = obj["spec"].get("selector") or {}
            selected = [
                w
                for w in workloads
                if _selects(selector, w["spec"]["template"]["metadata"].get("labels") or {})
            ]
            ready = sum(w["spec"].get("replicas", 1) for w in selected)
            owners = sorted({owner_of(w["kind"], w["metadata"]["name"]) for w in selected})
            out[(kind, name)] = snap.service(obj, ready, owners)
    return snap.Snapshot(out)


_HEADER = (
    "# Desired testbed state (decision 0013): the canonical snapshot a clean testbed must\n"
    "# match. Generated from manifests/testbed and config/topology.yaml by\n"
    "# `make desired-state`. Do not edit by hand. tests/test_snapshot.py fails on drift.\n"
)


def render() -> str:
    import json

    import yaml

    data = json.loads(desired_snapshot().to_json())
    body = {"projection_version": snap.SNAPSHOT_PROJECTION_VERSION, "resources": data}
    return _HEADER + yaml.safe_dump(body, sort_keys=True)


def load_desired_state(path: Path = DESIRED_STATE_PATH) -> snap.Snapshot:
    import yaml

    data = yaml.safe_load(path.read_text())
    if data.get("projection_version") != snap.SNAPSHOT_PROJECTION_VERSION:
        raise ValueError("desired_state.yaml was generated by a different projection version")
    return snap.Snapshot({tuple(k.split("/", 1)): v for k, v in data["resources"].items()})


def main(argv: list[str]) -> int:
    if argv != ["write"]:
        print("usage: python -m safeops.environment.desired write", file=sys.stderr)
        return 2
    DESIRED_STATE_PATH.write_text(render())
    print(f"wrote {DESIRED_STATE_PATH.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
